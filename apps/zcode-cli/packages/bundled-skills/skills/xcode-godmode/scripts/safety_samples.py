    L.append("")
    L.append("| field | meaning |")
    L.append("|:------|:--------|")
    L.append("| `system` | the system prompt sent ahead of the probe |")
    L.append("| `prefill` | the seeded user/assistant conversation |")
    L.append("| `encode` | whether the probe query is obfuscated before sending |")
    L.append("")
    L.append("A sample is only a sample until it is tested: `apply()` runs one")
    L.append("against a probe and scores the answer.")
    L.append("")

    L.append("## Index")
    L.append("")
    L.append("| sample | system | prefill | encode | what it does |")
    L.append("|:-------|:------:|:-------:|:------:|:-------------|")
    for name, s in lib.items():
        L.append(f"| `{name}` | {'yes' if s['system'] else '—'} | "
                 f"{'yes' if s['prefill'] else '—'} | "
                 f"{'yes' if s['encode'] else '—'} | {s['note']} |")
    L.append("")

    for name, s in lib.items():
        L.append(f"## `{name}`")
        L.append("")
        if s["note"]:
            L.append(f"*{s['note']}*")
            L.append("")
        if s["system"]:
            L.append("### system")
            L.append("")
            L.append("```text")
            L.append(s["system"])
            L.append("```")
            L.append("")
        if s["prefill"]:
            L.append("### prefill")
            L.append("")
            for m in s["prefill"]:
                L.append(f"**{m['role']}**:")
                L.append("")
                L.append("```text")
