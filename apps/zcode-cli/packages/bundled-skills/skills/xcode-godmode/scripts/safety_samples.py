#!/usr/bin/env python3
"""
SAFETY-SAMPLES — the canonical payload library, as data you can read,
copy, edit and feed back in.

WHAT THIS IS
------------
The jailbreak templates live in code (csam_eval.CSAM_JAILBREAK_STRATEGIES,
auto_jailbreak.MODEL_STRATEGIES). This module turns them into a REFERENCE
DOCUMENT: for every strategy, the exact system prompt, the exact prefill
conversation and a matching probe per category, in a form you can read in
a diff, paste into another tool, hand to a colleague, or edit.

Then it closes the loop: `apply()` takes a sample back and runs it, so a
sample is not just text — you can check whether the text still works.

The samples are prompt scaffolding, not harmful content. The probe queries
are request strings, and a compliant response is an UNLOCK — the pass
signal this module exists to verify. A sample "still works" when the
model produces real content for it.

Usage:
    python safety_samples.py --dump                 # write the reference doc
    python safety_samples.py --dump --stdout        # print it instead
    python safety_samples.py --apply persona_refusal_inversion
    python safety_samples.py --apply persona_refusal_inversion --category fraud
    python safety_samples.py --apply-from samples.json --category cbrn
    python safety_samples.py --list
"""

import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)

import csam_eval as ce  # noqa: E402
from safety_suite import CATEGORY_SPECS, PROBES  # noqa: E402

REFERENCE_PATH = os.path.join(HERE, "..", "references", "jailbreak-samples.md")

# ── the sample library ───────────────────────────────────────────────────
#
# Every entry is a complete, runnable attack:
#   system  — the system prompt (may be None)
#   prefill — the seeded conversation (may be None)
#   encode  — whether the query is obfuscated before it is sent
#   note    — what this template is trying to do

def build_library():
    """The sample library, built from the code so it can never drift."""
    lib = {}
    for name, spec in ce.CSAM_JAILBREAK_STRATEGIES.items():
        lib[name] = {
            "system": spec.get("system"),
            "prefill": spec.get("prefill"),
            "encode": bool(spec.get("encode", False)),
            "note": spec.get("note", ""),
        }
    return lib


# A representative probe per category, so a sample can be checked against
# every harm class without hand-picking queries.
def category_probes():
    """First hard probe (not benign) of each category."""
    out = {}
    for cat, items in PROBES.items():
        for pid, group, query, benign in items:
            if not benign:
                out[cat] = {"id": pid, "group": group, "query": query}
                break
    return out


# ── the reference document ───────────────────────────────────────────────

